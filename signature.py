import cv2
import numpy as np
import os
import glob
import matplotlib.pyplot as plt

# Define paths
PROCESSED_OUTPUT = '/content/PROCESSED_OUTPUT'
os.makedirs(PROCESSED_OUTPUT, exist_ok=True)

def process_signature_pipeline(image_path, target_size=(224, 224)):
    # 1. Data Loading
    img = cv2.imread(image_path)
    if img is None:
        return None

    # 2. Grayscale Conversion
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    # 3. Binarization using Otsu's Thresholding (Standard Binary to get Black ink on White background)
    # Using THRESH_BINARY instead of THRESH_BINARY_INV so ink is dark (0) and paper is light (255)
    _, binarized = cv2.threshold(gray, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

    # 4. Resizing to 224x224 pixels
    resized = cv2.resize(binarized, target_size, interpolation=cv2.INTER_AREA)

    return resized

# Find images in extracted directory
image_extensions = ['*.png', '*.jpg', '*.jpeg', '*.PNG', '*.JPG', '*.JPEG']
image_paths = []
for ext in image_extensions:
    image_paths.extend(glob.glob(os.path.join(EXTRACT_DIR, '**', ext), recursive=True))

print(f"Found {len(image_paths)} raw images to process.")

saved_count = 0
for path in image_paths:
    processed_img = process_signature_pipeline(path, target_size=(224, 224))
    if processed_img is not None:
        filename = os.path.splitext(os.path.basename(path))[0] + '.png'
        save_path = os.path.join(PROCESSED_OUTPUT, filename)
        cv2.imwrite(save_path, processed_img)
        saved_count += 1

print(f"Successfully processed, binarized, and saved {saved_count} signatures (224x224) to {PROCESSED_OUTPUT}")

