import cv2
import numpy as np
import os
import glob

# Define paths
PROCESSED_OUTPUT = '/content/PROCESSED_OUTPUT'
os.makedirs(PROCESSED_OUTPUT, exist_ok=True)

def remove_background_to_transparent(image_path, threshold=200, padding=10):
    """
    Revert to simple first flow: Remove background and save as transparent PNG
    without aggressive upscaling modifications if preferred, but keeping layout tight.
    """
    # Load image
    img = cv2.imread(image_path, cv2.IMREAD_UNCHANGED)
    if img is None:
        return None

    # If image already has an alpha channel, extract color and alpha
    if len(img.shape) == 4 or img.shape[2] == 4:
        b, g, r, _ = cv2.split(img)
    else:
        b, g, r = cv2.split(img)

    # Convert to grayscale to identify background vs signature
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY) if len(img.shape) == 3 else b

    # Create Alpha mask: pixels darker than threshold are signature (opaque),
    # pixels lighter than threshold are background (transparent).
    # Using a soft thresholding to preserve anti-aliasing edges of the pen stroke.
    alpha = np.where(gray < threshold, 255, 0).astype(np.uint8)

    # Keep original colors for the signature stroke, but apply transparency mask
    rgba = cv2.merge([b, g, r, alpha])

    # Trim empty margin to auto-crop whitespace based on active alpha channel
    non_zero_coords = np.argwhere(alpha > 0)
    if non_zero_coords.size == 0:
        return rgba # Return as is if empty

    min_y, min_x = non_zero_coords.min(axis=0)
    max_y, max_x = non_zero_coords.max(axis=0)

    # Secure bounds with padding
    h, w = gray.shape
    min_y = max(0, min_y - padding)
    min_x = max(0, min_x - padding)
    max_y = min(h, max_y + padding)
    max_x = min(w, max_x + padding)

    cropped_rgba = rgba[min_y:max_y, min_x:max_x]
    return cropped_rgba

# Find images in extracted directory
image_extensions = ['*.png', '*.jpg', '*.jpeg', '*.PNG', '*.JPG', '*.JPEG']
image_paths = []
for ext in image_extensions:
    image_paths.extend(glob.glob(os.path.join(EXTRACT_DIR, '**', ext), recursive=True))

print(f"Found {len(image_paths)} raw images to process.")

saved_count = 0
for path in image_paths:
    processed_img = remove_background_to_transparent(path, threshold=200, padding=15)
    if processed_img is not None:
        filename = os.path.splitext(os.path.basename(path))[0] + '.png'
        save_path = os.path.join(PROCESSED_OUTPUT, filename)
        cv2.imwrite(save_path, processed_img)
        saved_count += 1

print(f"Successfully processed and saved {saved_count} transparent PNG signatures to {PROCESSED_OUTPUT}")

