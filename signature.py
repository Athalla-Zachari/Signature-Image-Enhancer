    for i, path in enumerate(sample_enhanced_paths):
        img = cv2.imread(path, cv2.IMREAD_UNCHANGED)
        h, w, _ = img.shape

        # Create a light gray grid pattern background to verify transparency
        bg = np.ones_like(img) * 255
        bg[:, :, 0] = 245
        bg[:, :, 1] = 245
        bg[:, :, 2] = 245

        # Alpha blend onto background
        alpha = img[:, :, 3] / 255.0
        for c in range(3):
            bg[:, :, c] = (1.0 - alpha) * bg[:, :, c] + alpha * img[:, :, c]

        axes[i].imshow(cv2.cvtColor(bg, cv2.COLOR_BGR2RGB))
        axes[i].set_title(f"{os.path.basename(path)}\nSize: {w}x{h} (Upscaled)")
